/// ─────────────────────────────────────────────────────────────────────────────
/// AppFontSizes — Typography Size Tokens
///
/// Centralized font size constants to maintain scale consistency.
/// ─────────────────────────────────────────────────────────────────────────────
library;

abstract final class AppFontSizes {
  /// 11sp — label small
  static const double labelSmall = 11;

  /// 12sp — label medium, body small
  static const double labelMedium = 12;
  static const double bodySmall = 12;

  /// 13sp — mono code font
  static const double mono = 13;

  /// 14sp — label large, body medium, title small
  static const double labelLarge = 14;
  static const double bodyMedium = 14;
  static const double titleSmall = 14;

  /// 16sp — body large, title medium
  static const double bodyLarge = 16;
  static const double titleMedium = 16;

  /// 22sp — title large
  static const double titleLarge = 22;

  /// 24sp — headline small
  static const double headlineSmall = 24;

  /// 28sp — headline medium
  static const double headlineMedium = 28;

  /// 32sp — headline large
  static const double headlineLarge = 32;

  /// 36sp — display small
  static const double displaySmall = 36;

  /// 45sp — display medium
  static const double displayMedium = 45;

  /// 57sp — display large
  static const double displayLarge = 57;
}
